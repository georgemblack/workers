// Bundles the browser app (src/client) into strings the Worker serves itself,
// written to src/generated/client.ts. Run before dev, check, test and deploy.
import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const result = await build({
  entryPoints: [new URL("src/client/main.tsx", root).pathname],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: "es2022",
  jsx: "automatic",
  jsxImportSource: "preact",
  legalComments: "none",
});
const styles = await readFile(new URL("src/client/styles.css", root), "utf8");
await mkdir(new URL("src/generated/", root), { recursive: true });
await writeFile(
  new URL("src/generated/client.ts", root),
  "// Generated by scripts/build-client.mjs. Do not edit.\n" +
    `export const script = ${JSON.stringify(result.outputFiles[0].text)};\n` +
    `export const styles = ${JSON.stringify(styles)};\n`,
);
